# Логика ежедневных напоминаний через библиотеку schedule
def send_daily_reminders():
  """Функция рассылки напоминаний пользователям в фоновом режиме."""
  print("🔄 Запуск планоровщика напоминаний...")
  for user_id in user_read_days.keys():
    # Пример текста ежедневного напоминания
    safe_send_message(
        user_id,
        "🔔 <b>Напоминание адвент-календаря:</b>\nНе забудь уделить пару"
        " минут себе и открыть новые материалы сегодняшнего дня! 🌟",
        parse_mode="HTML",
    )


def run_scheduler():
  """Фоновый поток для непрерывной работы расписания schedule."""
  # Настраиваем время ежедневного напоминания, например, на 19:00 утра
  schedule.every().day.at("19:00").do(send_daily_reminders)

  while True:
    schedule.run_pending()
    time.sleep(30)


# Запуск фонового потока для планировщика
scheduler_thread = threading.Thread(target=run_scheduler, daemon=True)
scheduler_thread.start()


